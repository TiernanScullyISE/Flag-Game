const fs = require("fs");
const path = require("path");
const vm = require("vm");

const repoRoot = path.resolve(__dirname, "..");
const outputPath = path.join(repoRoot, "regions-leaderboard-data.js");

function loadRegionGroups(){
  const context = vm.createContext({console});
  vm.runInContext(
    fs.readFileSync(path.join(repoRoot, "regions-generated-data.js"), "utf8"),
    context,
    {filename:"regions-generated-data.js"}
  );
  const regionSource = fs.readFileSync(path.join(repoRoot, "regions-data.js"), "utf8");
  vm.runInContext(
    `${regionSource}\n;globalThis.__REGION_GROUPS__ = REGION_GAME_GROUPS; globalThis.__REGION_ORDER__ = REGION_GAME_GROUP_ORDER;`,
    context,
    {filename:"regions-data.js"}
  );
  return {
    groups: context.__REGION_GROUPS__,
    order: context.__REGION_ORDER__
  };
}

function makeSetKey(value){
  return String(value || "")
    .toLowerCase()
    .normalize("NFD")
    .replace(/\p{Diacritic}/gu, "")
    .replace(/[^\p{L}\p{N} ]/gu, "")
    .trim()
    .replace(/\s+/g, "-") || "all";
}

function itemHasFlag(group, item){
  return !!(
    item.flagUrl
    || item.flagFile
    || item.generatedFlag
    || group.flagFileTemplate
    || group.key === "United States"
    || (Array.isArray(item.colours) && item.colours.length)
  );
}

function buildData(){
  const {groups, order} = loadRegionGroups();
  return order
    .map(key=>groups[key])
    .filter(group=>group && Array.isArray(group.items) && group.items.length > 1)
    .map(group=>{
      const items = group.items || [];
      const flagCount = items.filter(item=>itemHasFlag(group, item)).length || items.length;
      const label = group.label || group.key;
      return {
        key: group.key || label,
        label,
        setKey: makeSetKey(label),
        itemLabel: group.itemLabel || "region",
        itemPluralLabel: group.itemPluralLabel || "regions",
        total: items.length,
        flagCount
      };
    });
}

const data = buildData();
const body = `/* Auto-generated by scripts/build-region-leaderboard-data.js. */
var REGION_LEADERBOARD_GROUPS = ${JSON.stringify(data, null, 2)};
`;

fs.writeFileSync(outputPath, body, "utf8");
console.log(`Wrote ${data.length} region leaderboard groups to ${outputPath}`);
